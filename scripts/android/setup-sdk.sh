#!/usr/bin/env bash
# Installs the Android build toolchain without root, under $ANDROID_TOOLCHAIN_ROOT
# (default: $HOME/.android-sdk): a Temurin 21 JDK, the Android command-line tools,
# platform-tools, platform 36 and build-tools 36.0.0.
#
# Usage:
#   bash scripts/android/setup-sdk.sh
#   source "$HOME/.android-sdk/env.sh"
#
# Idempotent: anything already unpacked or installed is left alone. Downloads resume
# (-C -), so a run cut short by a timeout is finished by running it again.
set -euo pipefail

ROOT=${ANDROID_TOOLCHAIN_ROOT:-$HOME/.android-sdk}
JDK_DIR="$ROOT/jdk"
SDK_DIR="$ROOT/sdk"
CMDLINE_DIR="$SDK_DIR/cmdline-tools/latest"
JDK_URL="https://api.adoptium.net/v3/binary/latest/21/ga/linux/x64/jdk/hotspot/normal/eclipse"
# Pinned: the command-line tools release that ships sdkmanager supporting platform 36.
CMDLINE_ZIP_URL="https://dl.google.com/android/repository/commandlinetools-linux-13114758_latest.zip"
PLATFORM="platforms;android-36"
BUILD_TOOLS="build-tools;36.0.0"

die() { echo "setup-sdk: $*" >&2; exit 1; }

for bin in curl tar unzip; do
  command -v "$bin" >/dev/null 2>&1 || die "missing '$bin' (install it with your package manager)"
done

mkdir -p "$ROOT"

fetch() { # <url> <dest>
  local url=$1 dest=$2
  echo "setup-sdk: fetching $url"
  curl -fL --retry 3 --retry-delay 2 -C - -o "$dest" "$url"
}

# 1. JDK 21
if [ -x "$JDK_DIR/bin/java" ]; then
  echo "setup-sdk: JDK already at $JDK_DIR"
else
  echo "setup-sdk: JDK 21"
  fetch "$JDK_URL" "$ROOT/jdk.tar.gz.part"
  rm -rf "$ROOT/jdk-unpack"
  mkdir -p "$ROOT/jdk-unpack"
  tar -xzf "$ROOT/jdk.tar.gz.part" -C "$ROOT/jdk-unpack"
  rm -rf "$JDK_DIR"
  mv "$(find "$ROOT/jdk-unpack" -maxdepth 1 -mindepth 1 -type d | head -1)" "$JDK_DIR"
  rm -rf "$ROOT/jdk-unpack" "$ROOT/jdk.tar.gz.part"
fi
export JAVA_HOME="$JDK_DIR"
export PATH="$JAVA_HOME/bin:$PATH"

"$JDK_DIR/bin/java" -version 2>&1 | head -1

# 2. Android command-line tools
if [ -x "$CMDLINE_DIR/bin/sdkmanager" ]; then
  echo "setup-sdk: command-line tools already at $CMDLINE_DIR"
else
  echo "setup-sdk: Android command-line tools"
  fetch "$CMDLINE_ZIP_URL" "$ROOT/cmdline-tools.zip.part"
  rm -rf "$ROOT/cmdline-unpack"
  mkdir -p "$ROOT/cmdline-unpack"
  unzip -q -o "$ROOT/cmdline-tools.zip.part" -d "$ROOT/cmdline-unpack"
  mkdir -p "$SDK_DIR/cmdline-tools"
  rm -rf "$CMDLINE_DIR"
  mv "$ROOT/cmdline-unpack/cmdline-tools" "$CMDLINE_DIR"
  rm -rf "$ROOT/cmdline-unpack" "$ROOT/cmdline-tools.zip.part"
fi
export ANDROID_HOME="$SDK_DIR"
export ANDROID_SDK_ROOT="$SDK_DIR"
export PATH="$CMDLINE_DIR/bin:$SDK_DIR/platform-tools:$SDK_DIR/build-tools/36.0.0:$PATH"

# 3. Licences and packages
# `yes` is killed by SIGPIPE once sdkmanager stops reading. With pipefail on, that reads
# as a failed pipeline, so it is off for these two calls and the sdkmanager status is kept.
set +o pipefail
yes 2>/dev/null | "$CMDLINE_DIR/bin/sdkmanager" --sdk_root="$SDK_DIR" --licenses >/dev/null || true
yes 2>/dev/null | "$CMDLINE_DIR/bin/sdkmanager" --sdk_root="$SDK_DIR" \
  "platform-tools" "$PLATFORM" "$BUILD_TOOLS" | tail -3
status=${PIPESTATUS[1]}
set -o pipefail
[ "$status" -eq 0 ] || die "sdkmanager exited $status"

# 4. What later shells source
cat > "$ROOT/env.sh" <<EOF
# Generated by scripts/android/setup-sdk.sh
export JAVA_HOME="$JDK_DIR"
export ANDROID_HOME="$SDK_DIR"
export ANDROID_SDK_ROOT="$SDK_DIR"
export PATH="\$JAVA_HOME/bin:\$ANDROID_HOME/cmdline-tools/latest/bin:\$ANDROID_HOME/platform-tools:\$ANDROID_HOME/build-tools/36.0.0:\$PATH"
EOF

echo "setup-sdk: done"
echo "  JAVA_HOME=$JAVA_HOME"
echo "  ANDROID_HOME=$ANDROID_HOME"
echo "  source \"$ROOT/env.sh\""
